// npm run icons -> src/ui/icons.ts: the regular and fill weights of the Phosphor icons the desk uses, as plain SVG
// element data. Importing @phosphor-icons/react ships all six weights of every icon (about 180 KB for ~55 icons);
// this keeps two. Add an icon: put it in NAMES (desk name -> Phosphor component name) and run the script.
import { writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { pathToFileURL } from "node:url";

const NAMES = {
  towel: "Shower", bed: "Bed", drop: "Drop", broom: "Broom", check: "CheckCircle", snow: "Snowflake", bulb: "Lightbulb",
  flame: "Flame", wifi: "WifiHigh", tv: "Television", bottle: "BeerBottle", tray: "Tray", clock: "Clock", ear: "Ear",
  plus: "Plus", wrench: "Wrench", clip: "ClipboardText", chart: "ChartBar", gear: "Gear", warn: "Warning",
  cloudoff: "CloudSlash", cloud: "CloudCheck", chev: "CaretRight", x: "X", tick: "Check", hourglass: "Hourglass",
  undo: "ArrowUUpLeft", siren: "Siren", user: "UserSwitch", list: "List", hand: "Handshake", bell: "Bell",
  printer: "Printer", info: "Info", home: "HouseLine", bolt: "Lightning", sun: "Sun", device: "DeviceMobile",
  waves: "Waves", signout: "SignOut", backspace: "Backspace", star: "Star",
  // Request-type icons a hotel can pick (REQUEST_ICONS in src/domain/catalog.ts) and the list editor's arrows.
  spa: "FlowerLotus", shirt: "TShirt", key: "Key", car: "Car", suitcase: "Suitcase", food: "ForkKnife", coffee: "Coffee",
  firstaid: "FirstAid", phone: "Phone", trash: "Trash", plug: "Plug", bug: "Bug", pool: "SwimmingPool", baby: "Baby",
  up: "CaretUp", down: "CaretDown",
};

const require = createRequire(import.meta.url);
const base = require.resolve("@phosphor-icons/react").replace(/index\.cjs\.js$/, "");
const toList = (c) => (c == null ? [] : Array.isArray(c) ? c : [c]);
const out = {};
for (const [key, comp] of Object.entries(NAMES)) {
  const { default: defs } = await import(pathToFileURL(`${base}defs/${comp}.es.js`).href);
  out[key] = ["regular", "fill"].map((w) =>
    toList(defs.get(w).props.children).map((el) => {
      const { children, ...attrs } = el.props;
      if (children) throw new Error(`${comp} ${w}: nested elements are not supported`);
      return [el.type, attrs];
    }),
  );
}

const body = Object.entries(out).map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`).join("\n");
writeFileSync(
  new URL("../src/ui/icons.ts", import.meta.url),
  `// Generated by scripts/icons.mjs from @phosphor-icons/react (MIT). Do not edit by hand.\n` +
    `export type IconEl = [string, Record<string, string | number>];\n` +
    `export const ICONS: Record<string, [regular: IconEl[], fill: IconEl[]]> = {\n${body}\n};\n`,
);
console.log(`Wrote ${Object.keys(out).length} icons to src/ui/icons.ts`);
